/** Convierte un hex (#RRGGBB) a rgba con alpha — replica el `tint()` del prototipo. */
export function tint(hex: string, alpha: number): string {
  const n = parseInt(hex.slice(1), 16);
  const r = (n >> 16) & 255;
  const g = (n >> 8) & 255;
  const b = n & 255;
  return `rgba(${r},${g},${b},${alpha})`;
}
